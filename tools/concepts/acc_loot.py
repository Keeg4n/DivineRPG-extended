def clock_pocket(t):
    """Карманные часы: корпус меняет металл, по кругу пять гнёзд, на каждом уровне загорается камень следующего мира."""
    def fn(c):
        case = CASE[t - 1]
        c.f(RECT(7, 0, 8, 1), case)
        c.f(DISC(8, 8.5, 7.4), case)
        c.c(DISC(8, 8.5, 5.3), BONE[3])
        c.c(RING(8, 8.5, 5.3, .9), BONE[1])
        for k in range(5):
            a = -math.pi / 2 + k * 2 * math.pi / 5
            x, y = int(round(7.5 + math.cos(a) * 6.3)), int(round(8 + math.sin(a) * 6.3))
            c.c(RECT(x, y, x + 1, y + 1), GEM_HIGHLIGHT[k] if k < t else case[0])
        c.l(8, 8, 8, 4 + (5 - t) // 2, K)
        c.l(8, 8, 8 + min(t, 3), 9, RED[2])
        c.d(K, 8, 8)
    return fn


def clock_sand(t):
    """Песочные часы: песок цвета мира, рамка растёт с уровнем."""
    def fn(c):
        sand = GEMS[t - 1]
        fr = [WOOD, WOOD, SILV, GOLD, OBS][t - 1]
        c.f(RECT(3, 1, 12, 2), fr)
        c.f(RECT(3, 13, 12, 14), fr)
        c.f(POLY((4, 3), (12, 3), (8.8, 8), (12, 13), (4, 13), (7.2, 8)), ICE[1:])
        c.f(POLY((5, 3 + (5 - t)), (11, 3 + (5 - t)), (8.5, 8), (7.5, 8)), sand)
        c.f(POLY((7.5, 11 - t * .6), (8.5, 11 - t * .6), (11.5, 13), (4.5, 13)), sand)
        c.l(8, 8, 8, 11, sand[3])
        if t >= 2:
            c.f(RECT(2, 3, 2, 12), fr).f(RECT(13, 3, 13, 12), fr)
        if t >= 3:
            c.d(GEM_HIGHLIGHT[t - 1], 7, 1, 8, 1, 7, 14, 8, 14)
        if t >= 4:
            c.f(POLY((1, 2), (0, 0), (3, 1)), fr).f(POLY((14, 2), (15, 0), (12, 1)), fr).f(POLY((1, 13), (0, 15), (3, 14)), fr).f(POLY((14, 13), (15, 15), (12, 14)), fr)
        if t >= 5:
            c.d(RED[3], 2, 7, 13, 7, 2, 8, 13, 8)
    return fn


def clock_wheel(t):
    """Круг миров: циферблат из пяти секторов, новый уровень зажигает следующий; стрелка указывает на текущий мир."""
    def fn(c):
        c.f(RECT(7, 0, 8, 1), GOLD)
        c.f(DISC(8, 8.5, 7.4), GOLD)
        for x, y in DISC(8, 8.5, 5.6):
            a = math.atan2(y + .5 - 8.5, x + .5 - 8) + math.pi / 2
            k = int((a % (2 * math.pi)) / (2 * math.pi / 5)) % 5
            ramp = GEMS[k] if k < t else BRN
            light = 2 if k < t else 1
            c.p[(x, y)] = hexc(ramp[light + ((x + y) % 2 == 0 and k < t)])
        for k in range(5):
            a = -math.pi / 2 + k * 2 * math.pi / 5
            c.l(8, 8, 8 + math.cos(a) * 5.4, 8.5 + math.sin(a) * 5.4, K)
        c.f(DISC(8, 8.5, 1.5), GOLD)
    return fn


